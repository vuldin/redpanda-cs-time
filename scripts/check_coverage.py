#!/usr/bin/env python3
"""
Check for off-calendar work in a date range by cross-referencing YAPA
(ChromaDB tasks/memories) and Claude Code session history, so this doesn't
depend on an agent remembering to do it by hand each time.

This is READ-ONLY / advisory: it never writes to timesheet_*.json or
Clockify. It flags candidate signals for a human (or agent) to fold into
data/slack_extras_<range>.json using the existing sizing heuristic.

PRIVACY: by default this touches nothing outside this repo and makes no
network calls. Session-history scanning of ~/.claude/projects (every Claude
Code project on the machine, not just this one) and the optional YAPA/
ChromaDB cross-reference are both opt-in, via config/config.yaml's
`session_scan.mode` and `yapa.enabled` (see config/config.yaml.example).

Usage:
    python scripts/check_coverage.py --start 2026-07-25 --end 2026-08-28
    python scripts/check_coverage.py --start 2026-07-25 --end 2026-08-28 \
        --timesheet data/timesheet_jul25_aug28.json
"""

import argparse
import json
import os
import re
import sys
from datetime import datetime, timedelta
from typing import Dict, List, Optional, Tuple

import requests

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from config.timesheet_config import build_customer_aliases, load_timesheet_config  # noqa: E402

CLAUDE_PROJECTS_DIR = os.path.expanduser("~/.claude/projects")


def build_alias_patterns(customer_aliases: Dict[str, str]) -> List[Tuple[str, str]]:
    """Free text is far noisier than a calendar title: unbounded substring
    matching lets short aliases fire inside ordinary words (e.g. "ti" inside
    "instrumentation"). Word-boundary regex (same fix applied to
    CUSTOMER_TITLE_PATTERNS matching in generate_timesheet.py) and a length
    floor cut most of that out."""
    return [(re.escape(alias), norm) for alias, norm in customer_aliases.items()
            if len(alias) >= 4]


def infer_customer(text: Optional[str], alias_patterns: List[Tuple[str, str]]) -> Optional[str]:
    if not text:
        return None
    lowered = text.lower()
    for pattern, norm in alias_patterns:
        if re.search(r'\b' + pattern + r'\b', lowered):
            return norm
    return None


# Sessions generated by hooks/loops/title-generation/resume-replay rather than
# by a real user request -- these produce huge message counts on every
# single day and are not billable hands-on work.
_AUTOMATED_PREFIXES = (
    "<local-command-caveat>",
    "<conversation_history>",
    "generate the session title from this json array",
    "reply with exactly:",
)


def is_automated_session(first_text: Optional[str]) -> bool:
    if not first_text:
        return False
    lowered = first_text.strip().lower()
    return any(lowered.startswith(p) for p in _AUTOMATED_PREFIXES)


def date_in_range(date_str: str, start: str, end: str) -> bool:
    return start <= date_str[:10] <= end


# Gaps this long or longer are breaks (stepped away, slept, etc.), not active
# work, and get subtracted out of the span rather than counted as hours.
GAP_THRESHOLD_SECONDS = 30 * 60


def active_minutes(timestamps: List[str]) -> float:
    """Real wall-clock active time from a list of ISO timestamps on one date:
    first-to-last span, minus any gap >= GAP_THRESHOLD_SECONDS. Message COUNT
    alone is not a reliable hours signal -- a resumed session can log 1000+
    messages in under two hours, or dozens of messages in under a minute
    during a context-compaction/resume replay."""
    if len(timestamps) < 2:
        return 0.0
    parsed = sorted(datetime.fromisoformat(t.replace("Z", "+00:00")) for t in timestamps)
    span = (parsed[-1] - parsed[0]).total_seconds()
    gap_total = sum(
        (b - a).total_seconds() for a, b in zip(parsed, parsed[1:])
        if (b - a).total_seconds() >= GAP_THRESHOLD_SECONDS
    )
    return (span - gap_total) / 60.0


# ==============================================================================
# YAPA / ChromaDB (opt-in: config `yapa.enabled: true`)
# ==============================================================================

def chroma_reachable(chroma_url: str) -> bool:
    try:
        r = requests.get(f"{chroma_url}/api/v2/heartbeat", timeout=3)
        return r.ok
    except requests.RequestException:
        return False


def list_collections(api_base: str) -> List[Dict]:
    r = requests.get(f"{api_base}/collections", timeout=10)
    r.raise_for_status()
    return r.json()


def get_docs_by_type(api_base: str, collection_id: str, doc_type: str, limit: int = 1000) -> List[Dict]:
    r = requests.post(
        f"{api_base}/collections/{collection_id}/get",
        json={"where": {"type": doc_type}, "limit": limit,
              "include": ["documents", "metadatas"]},
        timeout=15,
    )
    r.raise_for_status()
    data = r.json()
    out = []
    for i, doc_id in enumerate(data.get("ids", [])):
        out.append({
            "id": doc_id,
            "content": data["documents"][i],
            "metadata": data["metadatas"][i],
        })
    return out


def scan_yapa(start: str, end: str, chroma_url: str) -> Dict[str, List[Dict]]:
    """Pull YAPA signal from every collection for [start, end]. Tasks are
    filtered on `completed_at` only (not created_at/updated_at) -- a task
    being created or edited doesn't mean hands-on time happened that day,
    but a task being COMPLETED in range means real work finished, and its
    `duration_minutes` (when set) is ground-truth hands-on effort, not a
    heuristic guess. Memories are collected for the JSON file only -- every
    substantive session produces memories, so printing them all to stdout is
    pure noise."""
    if not chroma_reachable(chroma_url):
        return {"error": f"ChromaDB not reachable at {chroma_url}"}

    api_base = f"{chroma_url}/api/v2/tenants/default_tenant/databases/default_database"
    start_ts = int(datetime.strptime(start, "%Y-%m-%d").timestamp())
    end_ts = int((datetime.strptime(end, "%Y-%m-%d") + timedelta(days=1)).timestamp())

    tasks, memories = [], []
    for coll in list_collections(api_base):
        name, cid = coll["name"], coll["id"]
        try:
            for doc in get_docs_by_type(api_base, cid, "task"):
                m = doc["metadata"]
                completed = m.get("completed_at")
                if completed and start_ts <= completed < end_ts:
                    tasks.append({
                        "id": doc["id"], "collection": name, "title": doc["content"],
                        "status": m.get("status"), "customer": m.get("customer"),
                        "created_at": m.get("created_at"),
                        "completed_at": completed,
                        "duration_minutes": m.get("duration_minutes"),
                        "notes": m.get("notes"),
                    })
            for doc in get_docs_by_type(api_base, cid, "memory"):
                m = doc["metadata"]
                created = m.get("created_at")
                if created and start_ts <= created < end_ts:
                    memories.append({
                        "id": doc["id"], "collection": name,
                        "content": doc["content"][:300],
                        "created_at": created, "tags": m.get("tags"),
                    })
        except requests.RequestException as e:
            print(f"  [warn] skipping collection '{name}': {e}", file=sys.stderr)
            continue

    return {"tasks": tasks, "memories": memories}


# ==============================================================================
# Claude Code session history (opt-in beyond this repo: `session_scan.mode`)
# ==============================================================================

def _claude_project_dirname(path: str) -> str:
    """Claude Code names a project's session directory after its absolute
    cwd path with every '/' replaced by '-' (e.g. /home/alice/work ->
    -home-alice-work). Used to scope the scan by directory name alone, so
    out-of-scope sessions are never opened."""
    return os.path.abspath(path).rstrip('/').replace('/', '-')


def _allowed_dirnames(mode: str, allowed_paths: List[str]) -> Optional[set]:
    """Returns the set of project-directory names in scope, or None for no
    filtering (mode == 'all'). mode == 'none' is handled by callers before
    this is reached."""
    if mode == 'this_repo':
        return {_claude_project_dirname(os.getcwd())}
    if mode == 'allowlist':
        return {_claude_project_dirname(p) for p in allowed_paths}
    if mode == 'all':
        return None
    raise ValueError(f"Unknown session_scan.mode: {mode!r}")


def _load_session_index_enrichment(allowed_dirnames: Optional[set]) -> Dict[str, Dict]:
    """sessions-index.json gives a nice summary/projectPath/messageCount, but
    it's only reliable for low-traffic project dirs -- a busy hub directory
    can sit with a single stale entry for months while dozens of real
    sessions accumulate as raw .jsonl files underneath it. So: use it
    opportunistically to enrich a session found by the raw scan below, never
    as the primary source."""
    by_session_id: Dict[str, Dict] = {}
    if not os.path.isdir(CLAUDE_PROJECTS_DIR):
        return by_session_id
    for entry in os.scandir(CLAUDE_PROJECTS_DIR):
        if not entry.is_dir():
            continue
        if allowed_dirnames is not None and entry.name not in allowed_dirnames:
            continue
        index_path = os.path.join(entry.path, "sessions-index.json")
        if not os.path.isfile(index_path):
            continue
        try:
            with open(index_path) as f:
                index = json.load(f)
        except (json.JSONDecodeError, OSError):
            continue
        for session in index.get("entries", []):
            sid = session.get("sessionId")
            if sid:
                by_session_id[sid] = session
    return by_session_id


def scan_sessions(start: str, end: str, session_scan_mode: str,
                   allowed_paths: List[str], alias_patterns: List[Tuple[str, str]]) -> List[Dict]:
    """Scan raw .jsonl session transcripts directly (per-line `timestamp` and
    `cwd` fields) for activity dated in [start, end], enriching with
    sessions-index.json's summary when available for that session id.
    A single session can span multiple days; each returned hit is a
    (date, session) pair with the message count AND the real active-minutes
    span (see `active_minutes`) for just that date, not the whole session, so
    a multi-day session doesn't get its total attributed to every day it
    touched.

    `session_scan_mode` gates how much of ~/.claude/projects is touched at
    all: 'none' (default) scans nothing and makes no filesystem access here;
    'this_repo' / 'allowlist' / 'all' are documented in config.yaml.example.
    """
    if session_scan_mode == 'none':
        return []
    if not os.path.isdir(CLAUDE_PROJECTS_DIR):
        return []

    allowed_dirnames = _allowed_dirnames(session_scan_mode, allowed_paths)
    index_by_id = _load_session_index_enrichment(allowed_dirnames)
    start_dt = datetime.strptime(start, "%Y-%m-%d")
    end_dt = datetime.strptime(end, "%Y-%m-%d") + timedelta(days=1)
    mtime_lo = (start_dt - timedelta(days=1)).timestamp()
    mtime_hi = (end_dt + timedelta(days=2)).timestamp()

    hits: List[Dict] = []
    for entry in os.scandir(CLAUDE_PROJECTS_DIR):
        if not entry.is_dir():
            continue
        if allowed_dirnames is not None and entry.name not in allowed_dirnames:
            continue
        for f in os.scandir(entry.path):
            if not f.name.endswith(".jsonl"):
                continue
            try:
                if not (mtime_lo <= f.stat().st_mtime <= mtime_hi):
                    continue
            except OSError:
                continue

            per_date_count: Dict[str, int] = {}
            per_date_timestamps: Dict[str, List[str]] = {}
            cwd = None
            first_user_text = None
            session_id = None
            try:
                with open(f.path, errors="replace") as fh:
                    for line in fh:
                        try:
                            rec = json.loads(line)
                        except json.JSONDecodeError:
                            continue
                        session_id = session_id or rec.get("sessionId")
                        cwd = cwd or rec.get("cwd")
                        ts = rec.get("timestamp")
                        if ts and date_in_range(ts, start, end):
                            d = ts[:10]
                            per_date_count[d] = per_date_count.get(d, 0) + 1
                            per_date_timestamps.setdefault(d, []).append(ts)
                        if (first_user_text is None and rec.get("type") == "user"
                                and isinstance(rec.get("message"), dict)):
                            content = rec["message"].get("content")
                            if isinstance(content, str) and content.strip():
                                first_user_text = content[:200]
                            elif isinstance(content, list):
                                for block in content:
                                    if isinstance(block, dict) and block.get("type") == "text":
                                        first_user_text = block["text"][:200]
                                        break
            except OSError:
                continue

            if not per_date_count:
                continue

            index_entry = index_by_id.get(session_id, {})
            project_path = index_entry.get("projectPath") or cwd or entry.name
            customer_guess = (infer_customer(project_path, alias_patterns)
                               or infer_customer(first_user_text, alias_patterns))

            first_prompt = index_entry.get("firstPrompt") or first_user_text
            for date_str, count in per_date_count.items():
                hits.append({
                    "session_id": session_id,
                    "date": date_str,
                    "project_path": project_path,
                    "customer_guess": customer_guess,
                    "summary": index_entry.get("summary"),
                    "first_prompt": first_prompt,
                    "message_count_this_date": count,
                    "active_minutes_this_date": round(
                        active_minutes(per_date_timestamps[date_str]), 1),
                    "session_file": f.path,
                    "automated": is_automated_session(first_prompt),
                })

    hits.sort(key=lambda h: (h["date"], h["session_id"] or ""))
    return hits


# ==============================================================================
# Report
# ==============================================================================

def load_daily_hours(timesheet_path: Optional[str]) -> Dict[str, int]:
    if not timesheet_path or not os.path.isfile(timesheet_path):
        return {}
    with open(timesheet_path) as f:
        entries = json.load(f)
    counts: Dict[str, int] = {}
    for e in entries:
        d = e["start"][:10]
        counts[d] = counts.get(d, 0) + 1
    return counts


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--start", required=True)
    ap.add_argument("--end", required=True)
    ap.add_argument("--timesheet", help="Optional generated timesheet_<range>.json, "
                                         "to show already-logged hours per day")
    ap.add_argument("--output", help="Where to write the JSON report "
                                      "(default: data/coverage_<start>_<end>.json)")
    ap.add_argument("--config", default="config/config.yaml", help="Path to config file")
    ap.add_argument("--session-scan-mode", choices=["none", "this_repo", "allowlist", "all"],
                    help="Override config's session_scan.mode for this run")
    ap.add_argument("--yapa", action="store_true",
                    help="Force-enable the YAPA/ChromaDB cross-reference for this run")
    args = ap.parse_args()

    cfg = load_timesheet_config(args.config)
    session_scan_mode = args.session_scan_mode or cfg.session_scan.mode
    yapa_enabled = args.yapa or cfg.yapa.enabled

    customer_aliases = build_customer_aliases(cfg.customers)
    alias_patterns = build_alias_patterns(customer_aliases)

    output = args.output or f"data/coverage_{args.start}_{args.end}.json"

    print(f"Checking YAPA (ChromaDB) and Claude Code session history for "
          f"{args.start}..{args.end}...\n")

    if yapa_enabled:
        yapa = scan_yapa(args.start, args.end, cfg.yapa.chroma_url)
        if "error" in yapa:
            print(f"  [warn] {yapa['error']} -- skipping YAPA check. "
                  f"Start it: docker run -d --name chromadb --restart unless-stopped "
                  f"-p 8000:8000 -v chromadb_data:/data chromadb/chroma")
            yapa = {"tasks": [], "memories": []}
    else:
        print("  YAPA/ChromaDB cross-reference disabled (yapa.enabled: false in "
              "config, or pass --yapa to force it on for this run).")
        yapa = {"tasks": [], "memories": []}

    if session_scan_mode == "none":
        print("  Claude Code session scan disabled (session_scan.mode: none in "
              "config, or pass --session-scan-mode to override). No filesystem "
              "access outside this repo, no network calls.\n")
    sessions = scan_sessions(args.start, args.end, session_scan_mode,
                              cfg.session_scan.allowed_paths, alias_patterns)
    daily_hours = load_daily_hours(args.timesheet)

    report = {"range": [args.start, args.end], "yapa": yapa, "sessions": sessions}
    with open(output, "w") as f:
        json.dump(report, f, indent=2)

    print(f"YAPA: {len(yapa['tasks'])} task(s) completed in range "
          f"({len(yapa['memories'])} memories also touched in range -- see {output}, "
          f"not printed here: too noisy to be a signal by itself).")
    for t in yapa["tasks"]:
        dur = f"{t['duration_minutes']}min" if t["duration_minutes"] else "no duration logged"
        completed_date = datetime.fromtimestamp(t["completed_at"]).strftime("%Y-%m-%d")
        print(f"  - [{completed_date}] task {t['id']} [{t['collection']}] "
              f"{t['title'][:70]!r} customer={t['customer']} ({dur})")

    print(f"\nClaude Code sessions active in range: {len(sessions)} (date, session) pairs")
    by_date: Dict[str, List[Dict]] = {}
    for s in sessions:
        by_date.setdefault(s["date"], []).append(s)

    print("\nPer-day summary (calendar hours already logged vs. signals found):")
    print("(hidden here, but still in the JSON report: sessions with <5 messages on "
          "that date, and automated hook/loop/title-gen/resume-replay sessions -- "
          "neither is a real hands-on-work signal)")
    d = datetime.strptime(args.start, "%Y-%m-%d")
    end_dt = datetime.strptime(args.end, "%Y-%m-%d")
    while d <= end_dt:
        ds = d.strftime("%Y-%m-%d")
        hrs = daily_hours.get(ds)
        sess_today = [s for s in by_date.get(ds, [])
                      if s["message_count_this_date"] >= 5 and not s["automated"]]
        active_hrs_total = sum(s["active_minutes_this_date"] for s in sess_today) / 60.0
        flag = ""
        if sess_today and (hrs is None or hrs <= 6):
            flag = "  <-- check: session activity on a thin/untracked day"
        if hrs is not None or sess_today:
            active_note = f", ~{active_hrs_total:.1f}h active (real span)" if sess_today else ""
            print(f"  {ds} ({d.strftime('%a')}): "
                  f"{hrs if hrs is not None else '?'}h logged, "
                  f"{len(sess_today)} session(s){active_note}{flag}")
        for s in sess_today:
            mins = s["active_minutes_this_date"]
            span_note = f"~{mins / 60:.1f}h active" if mins >= 1 else "<1min active (likely a replay/burst, not hands-on)"
            print(f"      [{s['customer_guess'] or 'unknown'}] "
                  f"{s['summary'] or s['first_prompt']!r} "
                  f"({s['message_count_this_date']} msgs, {span_note}, {s['project_path']})")
        d += timedelta(days=1)

    print(f"\nFull report written to {output}")
    print("This is advisory only -- review and fold anything real into "
          "slack_extras_<range>.json by hand before regenerating the timesheet.")


if __name__ == "__main__":
    main()
